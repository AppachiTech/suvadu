    #[test]
    fn current_session_resolver_filters_ambiguous_cwd_candidates_by_opencode_agent() {
        // A Codex session and an OpenCode session sharing a directory: cwd
        // alone is ambiguous, and an explicit agent hint must narrow it.
        let (_dir, repo) = captured_session();
        insert_opencode_session(&repo, "ses-xyz", "/work/project");

        let ambiguous = call_json(
            &repo,
            "resolve_current_agent_session",
            &json!({"cwd": "/work/project"}),
            &McpConfig::default(),
        );
        assert_eq!(ambiguous["resolved"], false);
        assert_eq!(ambiguous["candidates"].as_array().unwrap().len(), 2);

        // Before the fix, "opencode" fell through to the filter's `_ =>
        // false` arm and silently zeroed every candidate instead of
        // narrowing down to the opencode session.
        let resolved = call_json(
            &repo,
            "resolve_current_agent_session",
            &json!({"cwd": "/work/project", "agent": "opencode"}),
            &McpConfig::default(),
        );
        assert_eq!(resolved["resolved"], true);
        assert_eq!(resolved["session"]["id"], "opencode-ses-xyz");
    }

    #[test]
    fn foreign_agent_can_save_summary_but_stale_revision_is_rejected() {
        let (_dir, repo) = captured_session();
        let mcp = McpConfig {
            allow_session_summaries: true,
            ..McpConfig::default()
        };
        let session = call_json(
            &repo,
            "get_agent_session",
            &json!({"session_id": "codex-native-123"}),
            &mcp,
        );
        let mut args = summary_args();
        args["session_id"] = json!("codex-native-123");
        args["source_revision"] = session["session"]["revision"].clone();
        args["source_ids"] = json!([session["events"][0]["id"]]);
        // Writer metadata can differ from the captured session's provider/model.
        args["agent"] = json!("claude");
        args["model"] = json!("claude-writer-model");
        call_json(&repo, "save_session_summary", &args, &mcp);
        let updated = call_json(
            &repo,
            "get_agent_session",
            &json!({"session_id": "codex-native-123"}),
            &mcp,
        );
        assert_eq!(updated["summaries"].as_array().unwrap().len(), 1);
        assert_eq!(updated["summaries"][0]["agent"], "claude");
        assert_eq!(updated["summaries"][0]["generated"], true);
        assert_eq!(updated["summaries"][0]["stale"], false);
        args["source_revision"] = json!("stale-revision");
        assert!(
            super::super::tools::call_tool(&repo, "save_session_summary", &args, &mcp)
                .unwrap_err()
                .to_lowercase()
                .contains("revision")
        );
        let excluded = McpConfig {
            exclude_dirs: vec!["/work/project".into()],
            ..mcp
        };
        args["source_revision"] = session["session"]["revision"].clone();
        assert!(
            super::super::tools::call_tool(&repo, "save_session_summary", &args, &excluded)
                .is_err()
        );
    }
