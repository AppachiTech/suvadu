fn pagination(args: &Value, mcp: &McpConfig) -> Result<(usize, usize), String> {
    let integer = |name: &str, default: usize| -> Result<usize, String> {
        args.get(name).map_or(Ok(default), |value| {
            value
                .as_u64()
                .and_then(|n| usize::try_from(n).ok())
                .ok_or_else(|| format!("{name} must be a non-negative integer"))
        })
    };
    let limit = integer(
        "limit",
        (mcp.default_limit as usize).clamp(1, MAX_PAGE_SIZE),
    )?;
    if !(1..=MAX_PAGE_SIZE).contains(&limit) {
        return Err(format!("limit must be between 1 and {MAX_PAGE_SIZE}"));
    }
    Ok((limit, integer("offset", 0)?))
}

fn session_id(args: &Value) -> Result<&str, String> {
    let id = args["session_id"].as_str().unwrap_or("");
    if !crate::util::is_valid_session_id(id) {
        return Err("A valid session_id is required".to_string());
    }
    Ok(id)
}

pub fn list(repo: &Repository, args: &Value, mcp: &McpConfig) -> Result<String, String> {
    let (limit, offset) = pagination(args, mcp)?;
    repo.list_ai_sessions(limit, offset, &mcp.exclude_dirs)
        .map(|result| result.to_string())
        .map_err(|e| e.to_string())
}

pub fn get(repo: &Repository, args: &Value, mcp: &McpConfig) -> Result<String, String> {
    let id = session_id(args)?;
    let (limit, offset) = pagination(args, mcp)?;
    let independent_offset = |name: &str| -> Result<Option<usize>, String> {
        args.get(name)
            .map(|value| {
                value
                    .as_u64()
                    .and_then(|number| usize::try_from(number).ok())
                    .ok_or_else(|| format!("{name} must be a non-negative integer"))
            })
            .transpose()
    };
    let event_offset = independent_offset("event_offset")?.unwrap_or(offset);
    let command_offset = independent_offset("command_offset")?.unwrap_or(offset);
    repo.get_ai_session_ranges(id, limit, event_offset, command_offset, &mcp.exclude_dirs)
        .map(|result| result.to_string())
        .map_err(|e| e.to_string())
}

fn prefixed_session_id(native_id: &str, agent: &str) -> Result<String, String> {
    if !crate::util::is_valid_session_id(native_id) {
        return Err("native_id must be a safe session identifier".to_string());
    }
    match agent {
        "openai-codex" | "codex" => Ok(format!("codex-{native_id}")),
        "claude-code" | "claude" => Ok(format!("claude-{native_id}")),
        "opencode" => Ok(format!("opencode-{native_id}")),
        _ => Err("agent must be openai-codex/codex, claude-code/claude, or opencode".to_string()),
    }
}

fn resolved(repo: &Repository, id: &str, source: &str, mcp: &McpConfig) -> Option<Value> {
    repo.get_ai_session(id, 1, 0, &mcp.exclude_dirs)
        .ok()
        .map(|result| {
            json!({
                "resolved":true,"session_id":id,"source":source,
                "session":result["session"],
                "capture_lag_note":"The current in-progress turn is imported at Stop/SessionEnd, so this session can lag until the turn finishes."
            })
        })
}

pub fn resolve(repo: &Repository, args: &Value, mcp: &McpConfig) -> Result<String, String> {
    if let Some(id) = args.get("session_id").and_then(Value::as_str) {
        if !crate::util::is_valid_session_id(id) {
            return Err("session_id must be a safe session identifier".to_string());
        }
        return resolved(repo, id, "explicit_session_id", mcp)
            .ok_or_else(|| "Explicit session was not found or is excluded".to_string())
            .map(|value| value.to_string());
    }
    if let Some(native_id) = args.get("native_id").and_then(Value::as_str) {
        let agent = args.get("agent").and_then(Value::as_str).unwrap_or("");
        let id = prefixed_session_id(native_id, agent)?;
        return resolved(repo, &id, "explicit_native_id", mcp)
            .ok_or_else(|| "Native session was not found or is excluded".to_string())
            .map(|value| value.to_string());
    }

    for (variable, agent) in [
        ("CODEX_THREAD_ID", "openai-codex"),
        ("CLAUDE_SESSION_ID", "claude-code"),
        ("CLAUDE_CODE_SESSION_ID", "claude-code"),
    ] {
        if let Ok(native_id) = std::env::var(variable) {
            if let Ok(id) = prefixed_session_id(&native_id, agent) {
                if let Some(value) = resolved(repo, &id, variable, mcp) {
                    return Ok(value.to_string());
                }
            }
        }
    }

    let cwd = args
        .get("cwd")
        .and_then(Value::as_str)
        .map(str::to_owned)
        .or_else(|| {
            std::env::current_dir()
                .ok()
                .map(|path| path.to_string_lossy().into_owned())
        });
    let agent = args.get("agent").and_then(Value::as_str);
    let listed = repo
        .list_ai_sessions(100, 0, &mcp.exclude_dirs)
        .map_err(|error| error.to_string())?;
    let matched = listed["sessions"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|session| {
            cwd.as_deref().is_some_and(|cwd| session["cwd"] == cwd)
                && agent.is_none_or(|agent| match agent {
                    "codex" | "openai-codex" => session["agent"] == "openai-codex",
                    "claude" | "claude-code" => session["agent"] == "claude-code",
                    "opencode" => session["agent"] == "opencode",
                    _ => false,
                })
        })
        .cloned()
        .collect::<Vec<_>>();
    let truncated = matched.len() > MAX_CANDIDATES;
    let mut candidates = matched;
    candidates.truncate(MAX_CANDIDATES);
    // With no directory to match against, nothing here is evidence that a
    // session is *this* session, so the caller sees the unfiltered recent
    // list as candidates rather than a pick.
    if cwd.is_none() {
        let fallback = listed["sessions"]
            .as_array()
            .into_iter()
            .flatten()
            .take(MAX_CANDIDATES)
            .cloned()
            .collect::<Vec<_>>();
        return Ok(cwd_resolution(None, fallback, false).to_string());
    }
    Ok(cwd_resolution(cwd.as_deref(), candidates, truncated).to_string())
}

/// At most this many candidates are returned for the user to choose from.
const MAX_CANDIDATES: usize = 10;

/// Decide what to return once the candidate list is known. Kept separate
/// from the lookup so each branch is directly testable, and so the
/// "convenient pick" cases are impossible to reintroduce by accident: no
/// directory means no resolution, and more than one match is always the
/// user's choice, never the newest one.
fn cwd_resolution(cwd: Option<&str>, candidates: Vec<Value>, truncated: bool) -> Value {
    const LAG: &str = "The current in-progress turn is imported at Stop/SessionEnd, so this session can lag until the turn finishes.";
    if cwd.is_none() {
        return json!({
            "resolved": false,
            "reason": "No working directory was available to match against, so no session was chosen. Pass cwd, or ask the user for an explicit session_id.",
            "candidates": candidates,
            "candidates_truncated": truncated,
            "capture_lag_note": LAG
        });
    }
    if candidates.len() == 1 {
        let session = candidates.into_iter().next().unwrap_or(Value::Null);
        return json!({
            "resolved": true,
            "session_id": session["id"],
            "source": "unambiguous_cwd",
            "match_reason": format!("Only captured session in {}", cwd.unwrap_or_default()),
            "verify_note": "Matched on working directory alone, not on this agent's own session identity. If the session below is not the work in progress, ask the user for an explicit session_id.",
            "session": session,
            "capture_lag_note": LAG
        });
    }
    json!({
        "resolved": false,
        "reason": if candidates.is_empty() {
            "No captured session matches the available agent and directory hints".to_string()
        } else {
            format!("{} captured sessions match; ask the user to choose a session ID", candidates.len())
        },
        "candidates": candidates,
        "candidates_truncated": truncated,
        "capture_lag_note": "The current in-progress turn is imported at Stop/SessionEnd, so retry after the turn finishes if the expected session is missing."
    })
}

/// Shared preflight, also called by the server before opening a writable database.
pub fn summary_input(args: &Value, mcp: &McpConfig) -> Result<SummaryInput, String> {
    if !mcp.allow_session_summaries
        || mcp
            .disabled_tools
            .iter()
            .any(|name| name == "save_session_summary")
    {
        return Err("Tool 'save_session_summary' is disabled; enable mcp.allow_session_summaries and remove it from mcp.disabled_tools to allow writes".to_string());
    }
    session_id(args)?;
    let input: SummaryInput = serde_json::from_value(args.clone())
        .map_err(|e| format!("Invalid summary arguments: {e}"))?;
    if input.text.trim().is_empty()
        || input.text.len() > MAX_SUMMARY_BYTES
        || input.text.chars().count() > MAX_SUMMARY_CHARS
    {
        return Err(
            "Summary text must be nonempty and at most 16000 characters / 64000 bytes".to_string(),
        );
    }
    if input.source_revision.trim().is_empty()
        || input.agent.trim().is_empty()
        || input.model.trim().is_empty()
    {
        return Err("source_revision, agent, and model must be nonempty".to_string());
    }
    if input.source_ids.is_empty() || input.source_ids.iter().any(|id| id.trim().is_empty()) {
        return Err("At least one nonempty source ID is required".to_string());
    }
    if input
        .base_summary_id
        .as_deref()
        .is_some_and(|id| id.trim().is_empty() || id.len() > 128)
    {
        return Err("base_summary_id must be a nonempty identifier".to_string());
    }
    Ok(input)
}

pub fn save(repo: &Repository, args: &Value, mcp: &McpConfig) -> Result<String, String> {
    let input = summary_input(args, mcp)?;
    repo.save_ai_summary(&input, &mcp.exclude_dirs)
        .map(|result| result.to_string())
        .map_err(|e| e.to_string())
}

