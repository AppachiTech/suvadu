//! Antigravity agent command capture.
//!
//! Antigravity's agent runs each command as `zsh -c '<command>'` from its
//! language server: a non-interactive shell that never reads `~/.zshrc`, so
//! the ordinary shell hooks never see it, and in which `preexec`/`precmd`
//! never fire anyway. zsh does read `~/.zshenv` there and exposes the command
//! as `$ZSH_EXECUTION_STRING`, so `suv init antigravity` writes a capture
//! script and a guarded block in `~/.zshenv` that sources it only in those
//! shells. The script records the command when the shell exits.
use std::path::{Path, PathBuf};

use super::{agent_hook, shell_escape};

/// The capture script's file name in `~/.config/suvadu/hooks/`.
pub const SCRIPT_NAME: &str = "antigravity-zsh.sh";

const BLOCK_START: &str = "# >>> suvadu antigravity >>>";
const BLOCK_END: &str = "# <<< suvadu antigravity <<<";

/// The zsh script sourced from `~/.zshenv` in Antigravity's agent shells.
///
/// It carries the `# suvadu-hook:` metadata line so `suv doctor` can check
/// the saved binary without running it.
pub fn capture_script(binary: &str) -> String {
    let metadata = serde_json::json!({"binary": binary, "target": "add"});
    let escaped = shell_escape(binary);
    format!(
        r#"# Suvadu - Antigravity agent command capture, generated by suv init antigravity
# suvadu-hook: {metadata}
# Sourced from ~/.zshenv only in the non-interactive `zsh -c` shells that
# Antigravity's agent runs its commands in. Records the command at exit.

# A zsh started by an agent command is part of that command, not a new one.
[[ -z "$_SUVADU_AG_CAPTURE" ]] || return 0
export _SUVADU_AG_CAPTURE=1

zmodload zsh/datetime 2>/dev/null || return 0
typeset -g _suvadu_ag_bin={escaped}
[[ -x "$_suvadu_ag_bin" ]] || _suvadu_ag_bin="${{commands[suv]:-}}"
[[ -n "$_suvadu_ag_bin" ]] || return 0

# Milliseconds since the epoch, in REPLY. '.' decimal point whatever the locale.
_suvadu_ag_ms() {{
    emulate -L zsh
    local LC_ALL=C
    typeset -g REPLY=$(( ${{EPOCHREALTIME%.*}} * 1000 + 10#${{${{EPOCHREALTIME#*.}}:0:3}} ))
}}

typeset -g _suvadu_ag_cmd="$ZSH_EXECUTION_STRING"
typeset -g _suvadu_ag_start_pwd="$PWD"
_suvadu_ag_ms
typeset -g _suvadu_ag_start="$REPLY"

_suvadu_ag_record() {{
    local exit_code=$?
    emulate -L zsh
    _suvadu_ag_ms
    local -a start_dir=()
    [[ "$_suvadu_ag_start_pwd" != "$PWD" ]] && start_dir=(--start-cwd "$_suvadu_ag_start_pwd")
    # One session per language server, so one IDE run's commands group together.
    "$_suvadu_ag_bin" add \
        --session-id "antigravity-$PPID" \
        --command "$_suvadu_ag_cmd" \
        --cwd "$PWD" \
        --exit-code "$exit_code" \
        --started-at "$_suvadu_ag_start" \
        --ended-at "$REPLY" \
        --executor-type agent \
        --executor antigravity "${{start_dir[@]}}" </dev/null >/dev/null 2>&1
    return $exit_code
}}
zshexit_functions+=(_suvadu_ag_record)

# zsh execs the last command of `zsh -c` in place of the shell, which would
# skip zshexit; any EXIT trap stops that. A trap the command sets itself
# replaces this one and still stops it.
trap ':' EXIT
"#
    )
}

/// The `~/.zshenv` block that loads `script`. The test is cheap enough for
/// every zsh on the machine: it sources nothing outside Antigravity's agent.
fn block(script: &Path) -> String {
    let script = shell_escape(&script.to_string_lossy());
    format!(
        "{BLOCK_START}\n\
         # Records Antigravity agent commands (suv init antigravity); inert in any other shell.\n\
         if [[ -n \"$ANTIGRAVITY_AGENT\" && ! -o interactive && -n \"$ZSH_EXECUTION_STRING\" && -r {script} ]]; then\n\
         \x20   source {script}\n\
         fi\n\
         {BLOCK_END}\n"
    )
}

/// Byte range of the Suvadu block in `contents`, including its end marker's
/// newline, if both markers are present in order.
fn block_range(contents: &str) -> Option<std::ops::Range<usize>> {
    let start = contents.find(BLOCK_START)?;
    let end_marker = start + contents[start..].find(BLOCK_END)?;
    let mut end = end_marker + BLOCK_END.len();
    if contents[end..].starts_with('\n') {
        end += 1;
    }
    Some(start..end)
}

/// `true` if `contents` holds the Suvadu block.
pub fn has_block(contents: &str) -> bool {
    block_range(contents).is_some()
}

/// `contents` with the block for `script` in it — replacing an older Suvadu
/// block in place, or appended — or `None` when it is already there.
pub fn with_block(contents: &str, script: &Path) -> Option<String> {
    let wanted = block(script);
    let updated = match block_range(contents) {
        Some(range) => {
            let mut s = contents.to_string();
            s.replace_range(range, &wanted);
            s
        }
        None if contents.is_empty() => wanted,
        None if contents.ends_with('\n') => format!("{contents}\n{wanted}"),
        None => format!("{contents}\n\n{wanted}"),
    };
    (updated != contents).then_some(updated)
}

/// `contents` without the Suvadu block, or `None` when there is none.
pub fn without_block(contents: &str) -> Option<String> {
    let range = block_range(contents)?;
    let mut s = contents.to_string();
    s.replace_range(range.clone(), "");
    // Drop the blank line `with_block` put before an appended block.
    if range.start > 0 && s[..range.start].ends_with("\n\n") {
        s.remove(range.start - 1);
    }
    Some(s)
}

/// The `.zshenv` zsh reads: `$ZDOTDIR/.zshenv`, else `~/.zshenv`.
pub fn zshenv_path(home: &Path) -> PathBuf {
    std::env::var_os("ZDOTDIR")
        .filter(|dir| !dir.is_empty())
        .map_or_else(|| home.to_path_buf(), PathBuf::from)
        .join(".zshenv")
}

/// The capture script's path under `home`.
pub fn script_path(home: &Path) -> PathBuf {
    home.join(".config/suvadu/hooks").join(SCRIPT_NAME)
}

/// What `suv doctor` should say about this integration's files, given the
/// script on disk (if any) and the `.zshenv` contents (if readable).
pub fn inspect(script: &Path, zshenv: Option<&str>) -> Option<Result<(), String>> {
    if !script.exists() {
        return None;
    }
    if let Err(reason) = agent_hook::inspect(script) {
        return Some(Err(format!("{SCRIPT_NAME}: {reason}")));
    }
    if !zshenv.is_some_and(has_block) {
        return Some(Err(".zshenv no longer loads the capture script".into()));
    }
    Some(Ok(()))
}

/// Install the capture script and the `.zshenv` block.
pub fn handle_init() -> Result<(), Box<dyn std::error::Error>> {
    let bin_path = std::env::current_exe()?.to_string_lossy().to_string();
    let home = PathBuf::from(std::env::var("HOME")?);

    let script = script_path(&home);
    if let Some(dir) = script.parent() {
        std::fs::create_dir_all(dir)?;
    }
    // Executable only so doctor's shared hook check accepts it; it is sourced.
    crate::util::atomic_write_with_mode(&script, &capture_script(&bin_path), 0o700)?;

    let zshenv = zshenv_path(&home);
    let before = match std::fs::read_to_string(&zshenv) {
        Ok(contents) => Some(contents),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(format!("cannot read {}: {e}", zshenv.display()).into()),
    };
    let mut backup_path = None;
    let changed = match with_block(before.as_deref().unwrap_or(""), &script) {
        Some(updated) => {
            if let Some(before) = &before {
                let name = format!(".zshenv.suvadu-backup-{}", uuid::Uuid::new_v4());
                let backup = zshenv.with_file_name(name);
                crate::util::atomic_write_with_mode(&backup, before, 0o600)?;
                backup_path = Some(backup);
                // Keeps a linked dotfile a link, and its mode.
                crate::util::atomic_write(&zshenv, &updated)?;
            } else {
                crate::util::atomic_write_with_mode(&zshenv, &updated, 0o644)?;
            }
            true
        }
        None => false,
    };

    let color = crate::util::color_enabled();
    let (b, r) = if color {
        ("\x1b[1m", "\x1b[0m")
    } else {
        ("", "")
    };
    let green = if color { "\x1b[32m" } else { "" };
    let cyan = if color { "\x1b[36m" } else { "" };

    println!("{b}Suvadu \u{2014} Antigravity Integration{r}");
    println!();
    println!("Capture script installed:");
    println!("  {}", script.display());
    println!();
    if changed {
        println!("{green}\u{2713}{r} {} now loads it", zshenv.display());
    } else {
        println!("{green}\u{2713}{r} {} already loads it", zshenv.display());
    }
    if let Some(backup) = &backup_path {
        println!("  Previous file backed up: {}", backup.display());
    }
    println!();
    println!("Antigravity's agent runs each command in its own `zsh -c` shell, which");
    println!("~/.zshrc never reaches. The block in .zshenv records those commands, and");
    println!("only those: it does nothing in any other shell.");
    println!();
    println!("Captured: each agent command with its exit code, duration and directory.");
    println!("Antigravity has no hooks for prompts or sessions, and a command it starts");
    println!("with `exec` or that is killed by a signal is not recorded.");
    println!();
    println!("Restart Antigravity, then verify with: {cyan}suv search --executor antigravity{r}");

    Ok(())
}

/// Remove the `.zshenv` block, keeping a backup. Returns `true` if one was
/// removed. The script goes with the hooks directory.
pub fn cleanup() -> Result<bool, Box<dyn std::error::Error>> {
    let home = PathBuf::from(std::env::var("HOME")?);
    let zshenv = zshenv_path(&home);
    let Ok(before) = std::fs::read_to_string(&zshenv) else {
        return Ok(false);
    };
    let Some(updated) = without_block(&before) else {
        return Ok(false);
    };
    let backup = zshenv.with_file_name(format!(".zshenv.suvadu-backup-{}", uuid::Uuid::new_v4()));
    crate::util::atomic_write_with_mode(&backup, &before, 0o600)?;
    crate::util::atomic_write(&zshenv, &updated)?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    const SCRIPT: &str = "/home/u/.config/suvadu/hooks/antigravity-zsh.sh";

    #[test]
    fn the_block_is_appended_after_existing_lines() {
        let updated = with_block("export EDITOR=vim\n", Path::new(SCRIPT)).unwrap();
        assert!(updated.starts_with("export EDITOR=vim\n\n# >>> suvadu antigravity >>>\n"));
        assert!(updated.ends_with("# <<< suvadu antigravity <<<\n"));
        assert!(updated.contains(&format!("source '{SCRIPT}'")));
    }

    #[test]
    fn a_file_without_a_final_newline_gets_one_before_the_block() {
        let updated = with_block("export EDITOR=vim", Path::new(SCRIPT)).unwrap();
        assert!(updated.starts_with("export EDITOR=vim\n\n# >>> suvadu"));
    }

    #[test]
    fn an_installed_block_is_left_as_it_is() {
        let once = with_block("", Path::new(SCRIPT)).unwrap();
        assert_eq!(with_block(&once, Path::new(SCRIPT)), None);
    }

    #[test]
    fn an_outdated_block_is_replaced_in_place() {
        let old = with_block("a=1\n", Path::new("/old/antigravity-zsh.sh")).unwrap();
        let old = format!("{old}b=2\n");
        let updated = with_block(&old, Path::new(SCRIPT)).unwrap();
        assert!(!updated.contains("/old/"), "{updated}");
        assert_eq!(updated.matches(BLOCK_START).count(), 1);
        assert!(updated.starts_with("a=1\n"));
        assert!(updated.ends_with("# <<< suvadu antigravity <<<\nb=2\n"));
    }

    #[test]
    fn removing_the_block_restores_the_original_file() {
        for original in ["export EDITOR=vim\n", "", "x=1"] {
            let installed = with_block(original, Path::new(SCRIPT)).unwrap();
            let removed = without_block(&installed).unwrap();
            let expected = if original.is_empty() || original.ends_with('\n') {
                original.to_string()
            } else {
                format!("{original}\n")
            };
            assert_eq!(removed, expected, "{original:?}");
        }
        assert_eq!(without_block("export EDITOR=vim\n"), None);
    }

    #[test]
    fn a_script_path_with_a_quote_stays_one_word() {
        let updated = with_block("", Path::new("/home/o'neil/s.sh")).unwrap();
        assert!(
            updated.contains(r"source '/home/o'\''neil/s.sh'"),
            "{updated}"
        );
    }

    #[test]
    fn the_script_carries_metadata_doctor_can_verify() {
        let dir = tempfile::tempdir().unwrap();
        let script = dir.path().join(SCRIPT_NAME);
        let exe = std::env::current_exe().unwrap();
        std::fs::write(&script, capture_script(&exe.to_string_lossy())).unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o700)).unwrap();
        }
        assert_eq!(agent_hook::inspect(&script), Ok(()));
    }

    #[test]
    fn doctor_needs_both_the_script_and_the_zshenv_block() {
        let dir = tempfile::tempdir().unwrap();
        let script = dir.path().join(SCRIPT_NAME);
        assert_eq!(inspect(&script, Some("")), None, "nothing installed");

        let exe = std::env::current_exe().unwrap();
        std::fs::write(&script, capture_script(&exe.to_string_lossy())).unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o700)).unwrap();
        }
        let installed = with_block("", &script).unwrap();
        assert_eq!(inspect(&script, Some(&installed)), Some(Ok(())));
        let missing = inspect(&script, Some("export EDITOR=vim\n")).unwrap();
        assert!(missing.unwrap_err().contains(".zshenv"));
        assert!(inspect(&script, None).unwrap().is_err());
    }
}
